export const EXPERT_PUZZLES: readonly Board[] = RAW.map((cells) => {
  /* A malformed board would fail later somewhere with no useful context, so it
     is caught here at module load instead. */
  if (cells.length !== CELL_COUNT) {
    throw new Error(
      `Expert puzzle has ${String(cells.length)} cells, expected ${String(CELL_COUNT)}.`,
    );
  }
  return [...cells];
});
